/* ============================================================
   売るときに引っかかるところを、条件から拾って出す。

   全部並べても読まれない。いま置いている条件で実際に効くものだけを、
   効く順に出す。判定はすべてここに置き、UIは並べるだけにする。

   level:
     danger … 放っておくと金額が変わる、または引き渡せない
     check  … 期限や手続き。忘れると面倒になる
     know   … 知っていると交渉や段取りで損をしない
   ============================================================ */

import { man, yen } from "./calc.js";

/**
 * どの段階にいるか。同じ条件でも、言うべきことは段階で変わる。
 * 契約が済んだ人に「価格を上げれば」と言っても意味がないし、
 * まだ何も動いていない人に申告書類の話をしても早い。
 */
export const STAGES = [
  { id: "guess", label: "まだ何も", full: "いくらくらいか知りたい" },
  { id: "quoted", label: "査定あり", full: "査定額をもらった" },
  { id: "listed", label: "売出し中", full: "売りに出している" },
  { id: "contracted", label: "契約済み", full: "売買契約が済んだ" },
];

export const LEVELS = [
  { id: "danger", label: "先に手を打つ" },
  { id: "check", label: "確かめる" },
  { id: "know", label: "知っておく" },
];

/**
 * input  … calc.simulate に渡したもの
 * result … calc.simulate の返り値
 * ownedYears … 実際に持っていた年数（1月1日基準ではないほう）
 * flags  … { stage, inherited, coOwned, buyingNext, breakEven }
 */
export function sellingNotes({ input, result, ownedYears = 0, flags = {} }) {
  const notes = [];
  const add = (n) => notes.push(n);
  const taxYears = input.heldYears || 0;
  const residence = Boolean(input.isResidence);
  const stage = flags.stage || "guess";
  /** その話がまだ間に合う段階か。済んだ話を並べても、読む気を削ぐだけ。 */
  const at = (...stages) => stages.includes(stage);

  /* ---------------------------------------- 先に手を打つ */

  if (result.net < 0) {
    add({
      id: "over-loan",
      level: "danger",
      title: "この価格では引き渡せない",
      body: `売却代金でローンを完済できないと、抵当権が外れず引き渡しができません。${man(
        result.shortfall
      )}を自己資金で用意するか、${
        flags.breakEven != null ? `${man(flags.breakEven)}以上で売るか` : "価格を上げるか"
      }のどちらかです。どちらも難しい場合は、住み替えローンや任意売却を金融機関に相談することになります。不動産会社より先に、借りている銀行に話を通してください。`,
    });
  }

  // 1月1日基準の判定は、実際の保有年数より最大1年ほど短い。
  // ここをまたいでいる人は、売る年をずらすだけで税額が変わる。
  if (ownedYears > 5 && taxYears <= 5 && result.taxable > 0) {
    const fixed = stage === "contracted";
    add({
      id: "cross-5y",
      level: "danger",
      title: fixed
        ? "引き渡し日が年をまたぐかどうかで、適用される税率の区分が変わる"
        : "所有期間が5年を超えるかどうかで、税率の区分が分かれる",
      body: `所有期間は「売った年の1月1日時点」で数えます。実際は${ownedYears.toFixed(
        1
      )}年持っていても、いまの売却時期だと${taxYears.toFixed(
        1
      )}年となり、短期譲渡の区分に入ります。短期の税率は39.63%、長期は20.315%です。判定は契約日ではなく<b>引き渡し日</b>によります。${
        fixed
          ? "契約が済んでいても引き渡し日がまだ確定していないなら、決済日の設定が税率の区分に影響します。買主にも引っ越しや融資実行の都合があるため、動かせるとは限りません。"
          : "引き渡しが翌年になれば、長期譲渡の区分になります。"
      }どの区分が適用されるか、実際の税額がいくらになるかは、他の所得の状況や個別の事情によります。税務署または税理士にご確認ください。`,
    });
  }

  if (residence && ownedYears > 10 && taxYears <= 10 && result.taxable > 0) {
    add({
      id: "cross-10y",
      level: "danger",
      title: "所有期間が10年を超えるかどうかで、軽減税率の適用が分かれる",
      body: `10年超所有の居住用財産の軽減税率は、1月1日基準で10年を超えている必要があります。実際は${ownedYears.toFixed(
        1
      )}年ですが、いまの売却時期では${taxYears.toFixed(
        1
      )}年です。この特例が適用される場合、課税譲渡所得6,000万円以下の部分の税率は14.21%、超える部分は20.315%です。適用には所有期間のほかにも要件があります。該当するかどうかは税務署または税理士にご確認ください。`,
    });
  }

  if (result.acquisition.method === "estimated" && result.tax.total > 0) {
    add({
      id: "unknown-cost",
      level: "danger",
      title: "購入時の契約書を探すと、税額が大きく下がる可能性がある",
      body: `いまは取得費を「売却価格の5%（${yen(
        result.acquisition.estimated
      )}）」として計算しています。実際にはもっと高く買っているのが普通なので、譲渡益が過大に出て、そのぶん税金が増えます。売買契約書、当時の通帳の振込記録、住宅ローンの金銭消費貸借契約書、購入時のパンフレットや価格表。このどれかが出てくれば、取得費として認められる余地があります。まず探してください。`,
    });
  }

  if (flags.buyingNext && result.deduction > 0) {
    add({
      id: "deduction-vs-mortgage",
      level: "danger",
      title: "3,000万円控除を使うと、新居の住宅ローン控除が使えなくなる",
      body: "売却で居住用財産の3,000万円特別控除（または買換え特例）を使った年と、その前後2年ずつを合わせた6年の間は、新しく買った家で住宅ローン控除を受けられません。どちらが得かは、今回の税額と、新居のローン控除13年分の合計を並べて比べる必要があります。売却の税額が小さいなら、控除を使わないほうが得になることがあります。",
    });
  }

  if (residence && !input.useDeduction && result.gross > 0) {
    add({
      id: "deduction-off",
      level: "danger",
      title: "3,000万円特別控除を使わない設定になっている",
      body: "この試算では特別控除を適用しない計算にしています。居住用財産の3,000万円特別控除には、前年・前々年に同じ特例を受けていないことなどの要件があり、新居で住宅ローン控除を受ける場合との関係もあります。ご自身が要件を満たすかどうかは、税務署または税理士にご確認ください。",
    });
  }

  /* ---------------------------------------- 確かめる */

  if (result.deduction > 0 || result.tax.total > 0 || result.gross < 0) {
    add({
      id: "must-file",
      level: "check",
      title: "税額が0円でも、確定申告は必要",
      body: "3,000万円特別控除も軽減税率も、確定申告をして初めて適用されます。申告しなければ特例は使えず、控除前の金額に課税されます。売った年の翌年2月16日から3月15日までに、譲渡所得の内訳書と、購入時・売却時の契約書の写しを添えて出します。",
    });
  }

  if (result.tax.resident > 0) {
    add({
      id: "resident-tax-timing",
      level: "check",
      title: `住民税 ${yen(result.tax.resident)} は翌年に来る`,
      body: "所得税は申告した年の3月に納めますが、住民税は売った年の翌年6月ごろから、4回に分けて（または給与天引きで）かかります。売却代金を使い切ったあとに請求が来る形になりやすいので、この額は最初から別に取り分けておいてください。国民健康保険料が上がることもあります。",
    });
  }

  if (residence) {
    add({
      id: "vacancy-limit",
      level: "check",
      title: "住まなくなってから3年目の年末が期限",
      body: "3,000万円特別控除は、住まなくなった日から3年を経過する日の属する年の12月31日までに売る必要があります。先に引っ越してから売りに出す場合は、この期限から逆算してください。また、前年・前々年にこの特例や買換え特例を受けていると使えません。",
    });
  }

  if (flags.inherited) {
    add({
      id: "inherited",
      level: "check",
      title: "相続で取得した家は、取得費も所有期間も引き継ぐ",
      body: "取得費は亡くなった方が買ったときの金額、所有期間も亡くなった方が取得した日から数えます。相続した日からではありません。古くから持っていた土地なら長期譲渡になりますが、取得費が分からず概算5%になりがちです。また、相続税を納めている場合には、相続税の申告期限の翌日から3年以内の譲渡について、納めた相続税の一部を取得費に加算できる特例があります。要件があり、このツールでは計算に入れていません。該当するかどうかは税務署または税理士にご確認ください。",
    });
  }

  if (flags.coOwned) {
    add({
      id: "co-owned",
      level: "check",
      title: "共有名義なら、3,000万円控除は持分ごとに使える",
      body: "夫婦で2分の1ずつ持っているなら、譲渡所得もそれぞれの持分で分け、特別控除も各自3,000万円ずつ使えます。合わせて6,000万円まで引ける計算です。ただし申告も各自で行います。このツールは1人ぶんの計算なので、自分の持分に対応する金額を入れ直してください。",
    });
  }

  if (result.gross < 0) {
    add({
      id: "loss-carryover",
      level: "check",
      title: "売却損が出ている。給与所得と相殺できる場合がある",
      body: `譲渡所得は ${man(
        result.gross
      )} のマイナスです。住んでいた家を売って損が出た場合、買い替えるとき（買換えの譲渡損失）や、売却価格が残債を下回るとき（特定居住用財産の譲渡損失）には、その損を給与所得などと損益通算し、引ききれない分を翌年以降3年間繰り越せる特例があります。所有期間5年超などの要件があり、このツールでは計算に入れていません。該当するかどうかは税務署または税理士にご確認ください。`,
    });
  }

  add({
    id: "tax-proration",
    level: "check",
    title: "固定資産税の日割り精算金は、値引きではなく売却収入",
    body: "引き渡し日を境に固定資産税を日割りして買主から受け取るのが慣行ですが、税務上これは税金の清算ではなく、売買代金の一部として譲渡収入に含めます。金額は数万円程度でも、申告のときに漏れやすいところです。",
  });

  /* ---------------------------------------- 知っておく */

  /* ---------------------------------------- 段階ごと */

  if (stage === "guess") {
    add({
      id: "stage-guess",
      stageNote: true,
      level: "know",
      title: "査定を頼む前に、自分の数字を持っておく",
      body: "査定を申し込んだ時点で、連絡先が不動産会社に渡ります。一括査定サイトなら6社から一斉に電話が来ることもあります。先に成約事例で当たりをつけておけば、出てきた査定額が高いのか安いのかを自分で判断できます。逆に何も持たずに聞くと、出された額が基準になってしまいます。",
    });
    add({
      id: "stage-guess-range",
      stageNote: true,
      level: "know",
      title: "売り出し価格と、実際に決まる価格は別物",
      body: "売り出し価格から値引き交渉が入って決まるのが普通です。地域や時期によりますが、数%から10%程度の差はよくあります。1点の数字ではなく、上下に振った幅で考えてください。",
    });
  }

  if (stage === "quoted") {
    add({
      id: "stage-quoted",
      stageNote: true,
      level: "danger",
      title: "査定額は「この額で売れる」という約束ではない",
      body: "媒介契約を取るために、相場より高い査定額を出す会社があります。契約したあとで「反応がないので下げましょう」となり、結局は相場に戻ります。3社ほどに出して、いちばん高い会社ではなく、<b>根拠にした成約事例を具体的に示せる会社</b>を選んでください。「近隣の〇年〇月成約、〇㎡、築〇年、〇万円」まで出せるかどうかで分かります。",
    });
    add({
      id: "stage-quoted-band",
      stageNote: true,
      level: "check",
      title: "もらった査定額を入れて、下振れも見ておく",
      body: "査定額をそのまま売却価格に入れ、そこから10%前後下がった場合の手取りも確かめてください。残債があるなら、下振れしたときに持ち出しになるかどうかが先に分かります。",
    });
  }

  if (stage === "listed") {
    add({
      id: "stage-listed",
      stageNote: true,
      level: "check",
      title: "反応がないなら3か月を目安に見直す",
      body: "問い合わせが来ないのか、内見はあるが決まらないのかで、原因が違います。問い合わせが来ないなら価格か写真、内見はあるが決まらないなら室内の状態や条件面です。不動産会社に、掲載後の閲覧数・問い合わせ数・内見数を出してもらってください。専任なら報告義務があります。",
    });
    add({
      id: "stage-listed-cut",
      stageNote: true,
      level: "know",
      title: "値下げは、検索の区切りをまたぐように",
      body: "買う側はポータルサイトで「3,000万円以下」のように区切って探します。3,050万円から2,980万円へ70万円下げると、それまで見えていなかった層の検索結果に入ります。10万円ずつ刻んで下げるより、区切りを1つまたぐほうが効きます。どこまで下げられるかは、手取りが0になる価格が下限です。",
    });
  }

  if (stage === "contracted") {
    add({
      id: "stage-contracted",
      stageNote: true,
      level: "check",
      title: "価格はもう動かない。ここから効くのは税金だけ",
      body: "売買契約が済んでいれば、手取りを増やす余地は税金の側にしか残っていません。特例を使えるかどうか、取得費をいくらで出せるかで、数十万から数百万円変わります。引き渡しまでに、下の書類を集めておいてください。",
    });
    add({
      id: "stage-contracted-docs",
      stageNote: true,
      level: "check",
      title: "確定申告に要るもの",
      body: "購入したときの売買契約書と領収書（取得費の証明）、今回の売買契約書、仲介手数料の領収書、印紙の領収書、登記費用の領収書、売却した不動産の登記事項証明書。居住用の特例を使うなら、売った家の所在地が載った戸籍の附票か住民票の除票も要ります。購入時の書類がいちばん出てこないので、先に探してください。",
    });
  }

  // 媒介契約を結ぶ前でなければ、手数料も契約の種類ももう決まっている。
  if (at("guess", "quoted")) {
    add({
      id: "brokerage-is-cap",
      level: "know",
      title: "仲介手数料は上限であって、定価ではない",
      body: `いまの試算では ${yen(
        result.costs.items.find((i) => i.id === "brokerage")?.yen || 0
      )} を入れています。これは宅地建物取引業法が定める報酬の上限で、これより低い額で契約することは違法ではありません。媒介契約を結ぶ前が交渉のタイミングです。ただし安さだけで選ぶと、広告費をかけてもらえないことがあります。`,
    });

    add({
      id: "media-contract",
      level: "know",
      title: "媒介契約は3種類。どれを選ぶかで売り方が変わる",
      body: "一般媒介は複数社に頼めますが、各社の本気度は下がりがちです。専任・専属専任は1社だけになる代わり、レインズへの登録と定期報告が義務づけられます。1社に絞るときは、他社からの問い合わせを断って自社で買主を見つけようとする「囲い込み」が起きていないか、レインズの登録証明書と問い合わせ状況を定期的に確認してください。",
    });
  }

  // 売り方をまだ選べる段階でだけ意味がある。
  if (at("guess", "quoted", "listed")) {
    add({
      id: "buyout",
      level: "know",
      title: "買取は早いが、相場の7割前後になる",
      body: "不動産会社が直接買う「買取」は、内見も広告も要らず1か月ほどで現金化できます。その代わり価格は仲介での相場の6〜8割です。仲介手数料はかかりません。住み替えの期限が決まっている、相続で早く分けたい、といった事情がなければ、まず仲介で出してみて、売れ残ったときの逃げ道として持っておくのが普通です。",
    });
  }

  // 告知は引き渡しまで効く。契約が済んでいても、見つかった不具合は伝えるほうが安い。
  add({
    id: "disclosure",
    level: "know",
    title: "知っている不具合は、隠さず書いたほうが安い",
    body: "雨漏り、シロアリ、給排水管の故障、越境、事件事故。引き渡し後に見つかると契約不適合責任を問われ、修補や代金減額、契約解除になることがあります。物件状況等報告書（告知書）に書いて売れば、その分は責任を負いません。値段が少し下がっても、書いておくほうが安く済みます。",
  });

  // 重い順に。同じ重さなら、いまの段階そのものの話を先に置く。
  const order = { danger: 0, check: 1, know: 2 };
  return notes.sort(
    (a, b) => order[a.level] - order[b.level] || Number(Boolean(b.stageNote)) - Number(Boolean(a.stageNote))
  );
}

/** 注意点の件数を段階ごとに数える。見出しのバッジ用。 */
export function countByLevel(notes) {
  const out = { danger: 0, check: 0, know: 0 };
  for (const n of notes) out[n.level] += 1;
  return out;
}
